                    'featured' => $data['featured'],
                    'is_verified' => true,
                    'verified_at' => now(),
                    'allow_follow' => true,
                    'show_email' => true,
                    'show_phone' => false,
                    'sort_order' => $data['sort_order'],
                ]
            );

            // Followers
            foreach ($students as $student) {
                if (! $teacher->followers()->where('user_id', $student->id)->exists()) {
                    $teacher->followers()->attach($student->id);
                }
            }

            // Dedicated Course
            if (! empty($data['course'])) {
                $cData = $data['course'];
                $course = Course::updateOrCreate(
                    ['slug' => $cData['slug']],
                    [
                        'instructor_id' => $user->id,
