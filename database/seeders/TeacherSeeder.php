                        'answer_body' => $data['qa']['answer'],
                        'is_private' => false,
                        'status' => 'published',
                        'published_at' => now(),
                    ]
                );
            }

            // Publications (Printed Book & E-Book)
            if (! empty($data['book'])) {
                Publication::updateOrCreate(
                    [
                        'user_id' => $user->id,
                        'slug' => Str::slug($data['slug'].'-book'),
                    ],
                    [
                        'category_id' => $bookStoreCat->id,
                        'title' => $data['book'],
                        'description' => $data['name'].' রচিত দ্বীনি গ্রন্থ। বিষয়বস্তুর সুবিন্যস্ত উপস্থাপনা ও আধুনিক জীবনের প্রাসঙ্গিক দলিল সমৃদ্ধ আলোচনা।',
                        'type' => 'book',
                        'external_url' => 'https://example.com/books',
                        'status' => 'published',
                        'published_at' => now(),
                    ]
                );
            }

            if (! empty($data['ebook'])) {
                Publication::updateOrCreate(
                    [
                        'user_id' => $user->id,
                        'slug' => Str::slug($data['slug'].'-ebook'),
                    ],
                    [
