                        'title' => $data['ebook'],
                        'description' => 'স্মার্টফোন ও ট্যাবলেটে সহজে পাঠযোগ্য ডিজিটাল পিডিএফ ও ই-বুক সংকলন।',
                        'type' => 'ebook',
                        'file_url' => 'https://example.com/ebooks/sample.pdf',
                        'status' => 'published',
                        'published_at' => now(),
                    ]
                );
            }
