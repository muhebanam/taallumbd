            Review::updateOrCreate(
                [
                    'teacher_id' => $teacher->id,
                    'course_id' => null,
                    'user_id' => $students[1]->id,
                ],
                [
                    'rating' => 5,
                    'comment' => 'আলহামদুলিল্লাহ, দ্বীনি ইলমের নির্ভরযোগ্য মারকায হিসেবে আত-তাআল্লুমে এই শিক্ষকের সাহচর্য আমাদের জন্য অনেক বড় নিয়ামত। অত্যন্ত বিনয়ী এবং প্রজ্ঞাপূর্ণ শিক্ষক।',
                    'status' => 'approved',
                ]
            );

            // Dedicated Q&A (Fatwa)
            if (! empty($data['qa'])) {
                Fatwa::updateOrCreate(
                    [
                        'teacher_id' => $teacher->id,
                        'question_title' => $data['qa']['title'],
                    ],
                    [
                        'question_user_id' => $students[2]->id,
                        'answered_by' => $user->id,
                        'category_id' => $fatwaCat->id,
