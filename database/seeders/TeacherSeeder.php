                        'rating' => 5,
                        'comment' => 'মাশাআল্লাহ! অত্যন্ত চমৎকার ও সমৃদ্ধ কোর্স। ওস্তাযার/ওস্তাদের বাচনভঙ্গি ও প্রাঞ্জল উপস্থাপনা দ্বীনের কঠিন বিষয়গুলো হৃদয়ঙ্গম করতে প্রভূত সাহায্য করেছে। আল্লাহ উনাকে উত্তম জাযা দান করুন।',
                        'status' => 'approved',
